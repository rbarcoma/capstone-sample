import { displayValue } from '@/lib/display-value';
import { StatCard } from '@/components/dss/stat-card';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { Button } from '@/components/ui/button';
import {
    Dialog,
    DialogContent,
    DialogHeader,
    DialogTitle,
} from '@/components/ui/dialog';
import type { ForecastResult } from '@/types';
import { Search } from 'lucide-react';
import { useMemo, useState } from 'react';

const monthNames = [
    'January',
    'February',
    'March',
    'April',
    'May',
    'June',
    'July',
    'August',
    'September',
    'October',
    'November',
    'December',
];

export default function ForecastResults({
    latestForecast,
    forecastHistory = [],
}: {
    latestForecast?: ForecastResult | null;
    forecastHistory: ForecastResult[];
}) {
    const [search, setSearch] = useState('');
    const [monthFilter, setMonthFilter] = useState('all');
    const [itemsPerPage, setItemsPerPage] = useState(10);
    const [currentPage, setCurrentPage] = useState(1);
    const [infoModal, setInfoModal] = useState<{
        title: string;
        content: string;
    } | null>(null);
    const latestForecastId = latestForecast?.id;

    const forecastInfo = {
        predictedConsumption: {
            title: 'Predicted Consumption',
            content:
                'Predicted Consumption is the estimated electricity consumption for the forecast period. It is generated by the trained Ridge (penalty 0.1) model using historical consumption, climate values, peak demand, lag features, trend, and seasonal month features.\n\nFormula:\npredicted_consumption = intercept + sum(coefficient × standardized_feature).\n\nThe target follows the latest complete actual dataset month. The recorded production time shows whether it was issued before, during, or after that target month.',
        },
        possibleChange: {
            title: 'Possible Change',
            content:
                'Possible Change shows the percentage difference between the predicted consumption and the previous month consumption.\n\nFormula:\nchange_percent = ((predicted_consumption - previous_consumption) / previous_consumption) × 100.\n\nA negative value means the model expects consumption to decrease. A positive value means the model expects consumption to increase.',
        },
        model: {
            title: 'Model',
            content:
                'Model shows the machine learning method used to generate the prediction. In this system, the prediction is generated using Ridge (penalty 0.1). Ridge (penalty 0.1) learns coefficients from the training dataset and uses those coefficients to estimate future electricity consumption.',
        },
    };

    const formatPredictionDate = (value?: string) => {
        if (!value) {
            return '-';
        }

        return new Intl.DateTimeFormat('en-PH', {
            dateStyle: 'medium',
            timeStyle: 'short',
        }).format(new Date(value));
    };

    const filteredForecasts = useMemo(() => {
        return forecastHistory.filter((item) => {
            const period = `${item.year}-${String(item.month).padStart(2, '0')}`;
            const monthName = monthNames[item.month - 1]?.toLowerCase() ?? '';
            const model = item.model_type?.toLowerCase() ?? '';
            const predictedBy = item.user?.name?.toLowerCase() ?? 'admin';
            const predictedAt = formatPredictionDate(
                item.predicted_at ?? item.created_at,
            ).toLowerCase();

            const matchesSearch =
                period.includes(search.toLowerCase()) ||
                monthName.includes(search.toLowerCase()) ||
                model.includes(search.toLowerCase()) ||
                predictedBy.includes(search.toLowerCase()) ||
                predictedAt.includes(search.toLowerCase()) ||
                String(item.predicted_consumption_kwh).includes(search);

            const matchesMonth =
                monthFilter === 'all' || item.month === Number(monthFilter);

            return matchesSearch && matchesMonth;
        });
    }, [forecastHistory, search, monthFilter]);

    const totalPages = Math.ceil(filteredForecasts.length / itemsPerPage);

    const paginatedForecasts = filteredForecasts.slice(
        (currentPage - 1) * itemsPerPage,
        currentPage * itemsPerPage,
    );

    return (
        <div className="space-y-6 p-6">
            <div>
                <h1 className="text-2xl font-semibold">Forecast Results</h1>
                <p className="text-sm text-muted-foreground">
                    Dataset-next-month consumption estimates and issuance history.
                </p>
            </div>

            <div className="grid gap-4 md:grid-cols-3">
                <StatCard
                    title="Predicted Consumption"
                    value={displayValue(latestForecast?.predicted_consumption_kwh, ' kWh')}
                    helper={latestForecast?.issuance_label}
                    onInfoClick={() =>
                        setInfoModal(forecastInfo.predictedConsumption)
                    }
                />
                <StatCard
                    title="Possible Change"
                    value={displayValue(latestForecast?.change_percent, '%')}
                    onInfoClick={() =>
                        setInfoModal(forecastInfo.possibleChange)
                    }
                />
                <StatCard
                    title="Model"
                    value={latestForecast?.model_type ?? 'No model'}
                    onInfoClick={() => setInfoModal(forecastInfo.model)}
                />
            </div>

            <Card className="rounded-lg">
                <CardHeader>
                    <div className="flex flex-col gap-4 md:flex-row md:items-center md:justify-between">
                        <CardTitle>Forecast History Table</CardTitle>

                        <div className="flex flex-col gap-2 md:flex-row">
                            <div className="relative">
                                <Search className="absolute left-3 top-3 h-4 w-4 text-muted-foreground" />
                                <Input
                                    className="w-full pl-9 md:w-64"
                                    placeholder="Search period or model..."
                                    value={search}
                                    onChange={(event) => {
                                        setSearch(event.target.value);
                                        setCurrentPage(1);
                                    }}
                                />
                            </div>

                            <select
                                className="rounded-md border bg-background px-3 py-2 text-sm"
                                value={monthFilter}
                                onChange={(event) => {
                                    setMonthFilter(event.target.value);
                                    setCurrentPage(1);
                                }}
                            >
                                <option value="all">All Months</option>
                                {monthNames.map((month, index) => (
                                    <option key={month} value={index + 1}>
                                        {month}
                                    </option>
                                ))}
                            </select>

                            <select
                                className="rounded-md border bg-background px-3 py-2 text-sm"
                                value={itemsPerPage}
                                onChange={(event) => {
                                    setItemsPerPage(Number(event.target.value));
                                    setCurrentPage(1);
                                }}
                            >
                                <option value={10}>10</option>
                                <option value={50}>50</option>
                                <option value={100}>100</option>
                            </select>
                        </div>
                    </div>
                </CardHeader>

                <CardContent className="overflow-x-auto">
                    <table className="w-full text-sm">
                        <thead>
                            <tr className="border-b bg-muted/80 text-left">
                                <th className="px-3 py-2 font-semibold">Period</th>
                                <th className="px-3 py-2 font-semibold">Prediction</th>
                                <th className="px-3 py-2 font-semibold">Change</th>
                                <th className="px-3 py-2 font-semibold">Model</th>
                                <th className="px-3 py-2 font-semibold">Produced</th>
                                <th className="px-3 py-2 font-semibold">Predicted By</th>
                            </tr>
                        </thead>

                        <tbody>
                            {paginatedForecasts.length > 0 ? (
                                paginatedForecasts.map((item) => {
                                    const isLatest = item.id === latestForecastId;

                                    return (
                                        <tr
                                            key={item.id}
                                            className={`border-b ${isLatest ? 'bg-primary/5 font-bold' : ''}`}
                                        >
                                            <td className="px-3 py-3">
                                                {item.year}-{String(item.month).padStart(2, '0')}
                                            </td>
                                            <td className="px-3 py-3">
                                                {displayValue(item.predicted_consumption_kwh, ' kWh')}
                                            </td>
                                            <td className="px-3 py-3">
                                                {displayValue(item.change_percent, '%')}
                                            </td>
                                            <td className="px-3 py-3">
                                                {item.model_type}
                                            </td>
                                            <td className="px-3 py-3">
                                                {item.issuance_label ?? 'Production time unavailable'}
                                            </td>
                                            <td className="px-3 py-3">
                                                {item.user?.name ?? 'Admin'}
                                            </td>
                                        </tr>
                                    );
                                })
                            ) : (
                                <tr>
                                    <td
                                        colSpan={6}
                                        className="px-3 py-8 text-center text-muted-foreground"
                                    >
                                        No forecast records found.
                                    </td>
                                </tr>
                            )}
                        </tbody>
                    </table>

                    <div className="mt-4 flex flex-col gap-3 md:flex-row md:items-center md:justify-between">
                        <p className="text-sm text-muted-foreground">
                            Showing {paginatedForecasts.length} of {filteredForecasts.length} forecasts
                        </p>

                        <div className="flex items-center gap-2">
                            <Button
                                variant="outline"
                                size="sm"
                                disabled={currentPage === 1}
                                onClick={() => setCurrentPage(currentPage - 1)}
                            >
                                Previous
                            </Button>

                            <span className="text-sm">
                                Page {currentPage} of {totalPages || 1}
                            </span>

                            <Button
                                variant="outline"
                                size="sm"
                                disabled={currentPage === totalPages || totalPages === 0}
                                onClick={() => setCurrentPage(currentPage + 1)}
                            >
                                Next
                            </Button>
                        </div>
                    </div>
                </CardContent>
            </Card>

            <Dialog open={!!infoModal} onOpenChange={() => setInfoModal(null)}>
                <DialogContent>
                    <DialogHeader>
                        <DialogTitle>{infoModal?.title}</DialogTitle>
                    </DialogHeader>

                    <p className="text-sm leading-relaxed whitespace-pre-line text-muted-foreground">
                        {infoModal?.content}
                    </p>
                </DialogContent>
            </Dialog>
        </div>
    );
}
